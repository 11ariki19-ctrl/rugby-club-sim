export const PREFS: Pref[] = RAW.map(([name, p]) => ({
  name,
  p,
  short: name === '北海道' ? '北海道' : name.slice(0, -1),
}));

export function publicPrefix(i: number): string {
  const n = PREFS[i].name;
  return n === '北海道' ? '北海道立' : PREFS[i].short + n.slice(-1) + '立';
}

export interface School {
  id: string;
  name: string;
  power: number;
  desc: string;
}

const lim = (x: number) => Math.min(5, Math.max(1, x));

/** 実在の学校ではなく、都道府県名から作る架空の高校 */
export function schoolsOf(i: number): School[] {
  const pf = PREFS[i];
  return [
    { id: `${i}-0`, name: `${publicPrefix(i)}中央高校`, power: lim(pf.p - 1), desc: '公立校。選手の力はまだ低めで、じっくり育てる' },
    { id: `${i}-1`, name: `${pf.short}学院高校`, power: pf.p, desc: '私立校。県内では標準的な戦力' },
    { id: `${i}-2`, name: `${pf.short}実業高校`, power: lim(pf.p + 1), desc: '強豪私立。選手層が厚く、評判も高い' },
  ];
}

